import { PITCH_POSITIONS } from './positions.js'
import { ROLES_IP, ROLES_OOP } from './fm26.js'

// Helper : construit un pion depuis un posId + rôles spécifiques
function pion(posId, rIP, rOOP) {
  const pos = PITCH_POSITIONS[posId]
  if (!pos) throw new Error(`Unknown posId: ${posId}`)
  // Fallback to first role if given role not in list
  const ipList  = ROLES_IP[pos.type]  || []
  const oopList = ROLES_OOP[pos.type] || []
  const finalIP  = ipList.includes(rIP)   ? rIP   : ipList[0]
  const finalOOP = oopList.includes(rOOP) ? rOOP  : oopList[0]
  return { posId, t: pos.type, x: pos.x, y: pos.y, rIP: finalIP, rOOP: finalOOP }
}

